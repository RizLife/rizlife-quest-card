revoke all on public.profiles, public.sections, public.section_students, public.section_join_codes, public.pending_student_requests, public.quests, public.submissions from anon, authenticated;
grant select on public.profiles, public.sections, public.section_students, public.quests, public.submissions to authenticated;
grant insert on public.submissions to authenticated;
grant insert, update on public.quests to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- The Node server uses a Supabase secret key, which maps to service_role.
-- RLS bypass still requires normal PostgreSQL table and sequence privileges.
grant all privileges on public.profiles, public.sections, public.section_students, public.section_join_codes, public.pending_student_requests, public.quests, public.submissions to service_role;
grant usage, select on all sequences in schema public to service_role;

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select to authenticated
using ((select auth.uid()) = id);

drop policy if exists "teachers read profiles" on public.profiles;
create policy "teachers read profiles" on public.profiles for select to authenticated
using ((select public.is_teacher()) and (select public.teaches_student(id)));

drop policy if exists "teachers read own sections" on public.sections;
create policy "teachers read own sections" on public.sections for select to authenticated
using ((select public.owns_section(id)));

drop policy if exists "students read enrolled sections" on public.sections;
create policy "students read enrolled sections" on public.sections for select to authenticated
using ((select public.is_enrolled_in_section(id)));

drop policy if exists "teachers read section enrollments" on public.section_students;
create policy "teachers read section enrollments" on public.section_students for select to authenticated
using ((select public.owns_section(section_id)));

drop policy if exists "students read own enrollments" on public.section_students;
create policy "students read own enrollments" on public.section_students for select to authenticated
using (student_id = (select auth.uid()));

drop policy if exists "authenticated read active quests" on public.quests;
create policy "authenticated read active quests" on public.quests for select to authenticated
using (
  ((select public.owns_section(section_id)))
  or (active = true and (select public.is_enrolled_in_section(section_id)))
);

drop policy if exists "teachers create quests" on public.quests;
create policy "teachers create quests" on public.quests for insert to authenticated
with check ((select public.is_teacher()) and (select public.owns_section(section_id)) and created_by = (select auth.uid()));

drop policy if exists "teachers update quests" on public.quests;
create policy "teachers update quests" on public.quests for update to authenticated
using ((select public.owns_section(section_id))) with check ((select public.owns_section(section_id)));

drop policy if exists "students read own submissions" on public.submissions;
create policy "students read own submissions" on public.submissions for select to authenticated
using (student_id = (select auth.uid()));

drop policy if exists "teachers read submissions" on public.submissions;
create policy "teachers read submissions" on public.submissions for select to authenticated
using (exists (select 1 from public.quests where id = submissions.quest_id and (select public.owns_section(section_id))));

drop policy if exists "students submit own evidence" on public.submissions;
create policy "students submit own evidence" on public.submissions for insert to authenticated
with check (
  student_id = (select auth.uid())
  and status = 'submitted'
  and feedback is null
  and reviewed_at is null
  and reviewed_by is null
  and exists (
    select 1
    from public.quests quest
    join public.section_students enrollment
      on enrollment.section_id = quest.section_id
    where quest.id = submissions.quest_id
      and quest.active = true
      and enrollment.student_id = (select auth.uid())
  )
);

