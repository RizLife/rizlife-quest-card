-- Run once in Supabase Dashboard > SQL Editor before deploying student self-registration.
create table if not exists public.pending_student_requests (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id) on delete cascade,
  student_id uuid not null unique references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 100),
  email text not null unique check (char_length(email) between 5 and 200),
  student_number text not null check (char_length(student_number) between 1 and 100),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid references public.profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists pending_student_requests_section_status_idx
  on public.pending_student_requests(section_id, status, created_at);

alter table public.pending_student_requests enable row level security;
revoke all on public.pending_student_requests from anon, authenticated;
grant all privileges on public.pending_student_requests to service_role;
grant usage, select on all sequences in schema public to service_role;
