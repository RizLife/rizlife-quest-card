-- Run once in Supabase Dashboard > SQL Editor before deploying join codes.
create table if not exists public.section_join_codes (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id) on delete cascade,
  code text not null check (code ~ '^RZ-[A-F0-9]{6}-[A-F0-9]{6}$'),
  code_hash text not null unique check (char_length(code_hash) = 64),
  created_by uuid not null references public.profiles(id) on delete cascade,
  -- Compatibility column: active codes are permanent and are invalidated only
  -- when revoked or replaced by their section's teacher.
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at > created_at)
);

create unique index if not exists section_join_codes_one_active_per_section_idx
  on public.section_join_codes(section_id) where revoked_at is null;
create index if not exists section_join_codes_lookup_idx
  on public.section_join_codes(code_hash, expires_at) where revoked_at is null;

alter table public.section_join_codes enable row level security;
revoke all on public.section_join_codes from anon, authenticated;
grant all privileges on public.section_join_codes to service_role;
grant usage, select on all sequences in schema public to service_role;
