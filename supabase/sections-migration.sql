-- Run once in Supabase SQL Editor for projects created before section support.

create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 50),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (teacher_id, name)
);

create table if not exists public.section_students (
  section_id bigint not null references public.sections(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  primary key (section_id, student_id)
);

alter table public.quests add column if not exists section_id bigint references public.sections(id) on delete cascade;

create index if not exists sections_teacher_idx on public.sections(teacher_id);
create index if not exists section_students_student_idx on public.section_students(student_id);
create index if not exists quests_section_idx on public.quests(section_id);

alter table public.sections enable row level security;
alter table public.section_students enable row level security;

revoke all on public.sections, public.section_students from anon, authenticated;
grant select on public.sections, public.section_students to authenticated;
grant all privileges on public.sections, public.section_students to service_role;
grant usage, select on all sequences in schema public to service_role;

drop policy if exists "teachers read own sections" on public.sections;
create policy "teachers read own sections" on public.sections for select to authenticated
using (teacher_id = (select auth.uid()));

drop policy if exists "students read enrolled sections" on public.sections;
create policy "students read enrolled sections" on public.sections for select to authenticated
using (exists (
  select 1 from public.section_students
  where section_id = sections.id and student_id = (select auth.uid())
));

drop policy if exists "teachers read section enrollments" on public.section_students;
create policy "teachers read section enrollments" on public.section_students for select to authenticated
using (exists (
  select 1 from public.sections
  where id = section_students.section_id and teacher_id = (select auth.uid())
));

drop policy if exists "students read own enrollments" on public.section_students;
create policy "students read own enrollments" on public.section_students for select to authenticated
using (student_id = (select auth.uid()));

drop policy if exists "authenticated read active quests" on public.quests;
create policy "authenticated read active quests" on public.quests for select to authenticated
using (
  ((select public.is_teacher()) and exists (
    select 1 from public.sections where id = quests.section_id and teacher_id = (select auth.uid())
  ))
  or (active = true and exists (
    select 1 from public.section_students
    where section_id = quests.section_id and student_id = (select auth.uid())
  ))
);
