-- RizLife Quest Card: Supabase schema and authorization.
-- Run this once in Supabase Dashboard > SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 100),
  student_number text,
  avatar_path text,
  role text not null default 'student' check (role in ('student', 'teacher')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 50),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (teacher_id, name)
);

create table if not exists public.section_students (
  section_id bigint not null references public.sections(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  primary key (section_id, student_id)
);

create table if not exists public.section_join_codes (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id) on delete cascade,
  code text not null check (code ~ '^RZ-[A-F0-9]{6}-[A-F0-9]{6}$'),
  code_hash text not null unique check (char_length(code_hash) = 64),
  created_by uuid not null references public.profiles(id) on delete cascade,
  -- Retained for compatibility with earlier deployments. Application join codes
  -- are permanent and use a far-future value; revocation controls validity.
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at > created_at)
);

create table if not exists public.pending_student_requests (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id) on delete cascade,
  student_id uuid not null unique references public.profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 100),
  email text not null unique check (char_length(email) between 5 and 200),
  student_number text not null check (char_length(student_number) between 1 and 100),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid references public.profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.quests (
  id bigint generated by default as identity primary key,
  quest_slot smallint not null check (quest_slot between 1 and 24),
  title text not null check (char_length(title) between 2 and 120),
  description text not null check (char_length(description) between 5 and 2000),
  requirement text not null check (char_length(requirement) between 2 and 500),
  section_id bigint references public.sections(id) on delete cascade,
  active boolean not null default true,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  quest_id bigint not null references public.quests(id) on delete cascade,
  evidence_type text not null check (evidence_type in ('link', 'text', 'image')),
  evidence text not null check (char_length(evidence) between 1 and 5000),
  status text not null default 'submitted' check (status in ('submitted', 'verified', 'rejected')),
  feedback text check (feedback is null or char_length(feedback) <= 2000),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id)
);

create index if not exists profiles_role_idx on public.profiles(role);
create unique index if not exists profiles_student_number_unique_idx on public.profiles(lower(student_number)) where student_number is not null and student_number <> '';
create index if not exists sections_teacher_idx on public.sections(teacher_id);
create index if not exists section_students_student_idx on public.section_students(student_id);
create unique index if not exists section_join_codes_one_active_per_section_idx on public.section_join_codes(section_id) where revoked_at is null;
create index if not exists section_join_codes_lookup_idx on public.section_join_codes(code_hash, expires_at) where revoked_at is null;
create index if not exists pending_student_requests_section_status_idx on public.pending_student_requests(section_id, status, created_at);
create index if not exists quests_section_idx on public.quests(section_id);
create unique index if not exists quests_section_slot_unique_idx on public.quests(section_id, quest_slot);
create index if not exists submissions_student_quest_idx on public.submissions(student_id, quest_id, id desc);
create index if not exists submissions_status_idx on public.submissions(status);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists quests_set_updated_at on public.quests;
create trigger quests_set_updated_at before update on public.quests
for each row execute function public.set_updated_at();

create or replace function public.is_teacher()
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'teacher' and active = true
  );
$$;

revoke all on function public.is_teacher() from public;
grant execute on function public.is_teacher() to authenticated;

-- SECURITY DEFINER helpers avoid circular RLS checks between classes and enrollments.
create or replace function public.owns_section(target_section_id bigint)
returns boolean language sql security definer stable set search_path = '' as $$
  select (select public.is_teacher()) and exists (
    select 1 from public.sections
    where id = target_section_id and teacher_id = (select auth.uid())
  );
$$;

create or replace function public.is_enrolled_in_section(target_section_id bigint)
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (select 1 from public.section_students where section_id = target_section_id and student_id = (select auth.uid()));
$$;

create or replace function public.teaches_student(target_student_id uuid)
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (
    select 1 from public.section_students enrollment
    join public.sections class on class.id = enrollment.section_id
    where enrollment.student_id = target_student_id and class.teacher_id = (select auth.uid())
  );
$$;

revoke all on function public.owns_section(bigint), public.is_enrolled_in_section(bigint), public.teaches_student(uuid) from public;
grant execute on function public.owns_section(bigint), public.is_enrolled_in_section(bigint), public.teaches_student(uuid) to authenticated;

